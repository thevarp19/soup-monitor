/**
 * Writes the before/after table into PERF.md (between the table markers) from the result files,
 * so that no number in PERF.md is typed by hand.
 *
 * usage: node perf/report.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';

interface Stat {
  median: number;
  min: number;
  max: number;
  n: number;
}
interface Summary {
  firstRenderMs: Stat | null;
  firstRenderAdjustedForUnthrottledWorkerMs: Stat | null;
  totalBlockingTimeBeforeFirstRenderMs: Stat | null;
  hoverMs_medianPerRun: Stat | null;
  hoverMs_maxPerRun: Stat | null;
  zoomMs: Stat | null;
  memory: Record<string, Stat | null>;
}
interface Result {
  label: string;
  commit: string;
  date: string;
  url: string;
  environment: { chrome: string; machine: string };
  settings: { cpuThrottlingRate: number; runs: number; viewport: { width: number; height: number }; deviceScaleFactor: number };
  summary: Summary;
  iterations: Array<{ workerMs: number | null }>;
}

const load = (f: string) => JSON.parse(readFileSync(f, 'utf8')) as Result;
const before = load('perf/results-before.json');
const afterV1 = load('perf/results-after-v1.json');
const after = load('perf/results-after.json');

const cell = (s: Stat | null | undefined, unit: string) => (s ? `**${s.median} ${unit}** (${s.min}–${s.max})` : 'n/a');
const change = (b: Stat | null | undefined, a: Stat | null | undefined) => {
  if (!b || !a || b.median === 0) return '';
  const pct = Math.round(((a.median - b.median) / b.median) * 100);
  return `${pct > 0 ? '+' : ''}${pct}%`;
};

const rows: Array<[string, (s: Summary) => Stat | null | undefined, string]> = [
  ['First render (navigation → loss chart drawn), measured', (s) => s.firstRenderMs, 'ms'],
  ['First render if the worker were throttled ×4 too (upper bound)¹', (s) => s.firstRenderAdjustedForUnthrottledWorkerMs, 'ms'],
  ['Total Blocking Time before first render', (s) => s.totalBlockingTimeBeforeFirstRenderMs, 'ms'],
  ['Hover → next paint, median of each run', (s) => s.hoverMs_medianPerRun, 'ms'],
  ['Hover → next paint, worst move of each run', (s) => s.hoverMs_maxPerRun, 'ms'],
  ['Zoom (mouseup → new range drawn)', (s) => s.zoomMs, 'ms'],
  ['Tab memory: renderer footprint (incl. worker)²', (s) => s.memory.rendererFootprintMB, 'MB'],
  ['measureUserAgentSpecificMemory (JS incl. worker)', (s) => s.memory.uaSpecificMB, 'MB'],
  ['JSHeapUsedSize — main thread only, NOT comparable³', (s) => s.memory.jsHeapUsedMB_mainThreadOnly, 'MB'],
];

const lines = [
  `| Metric | Before (naive) | After v1 | After (final) | Before → final |`,
  `|---|---|---|---|---|`,
  ...rows.map(([name, get, unit]) => `| ${name} | ${cell(get(before.summary), unit)} | ${cell(get(afterV1.summary), unit)} | ${cell(get(after.summary), unit)} | ${change(get(before.summary), get(after.summary))} |`),
  '',
  `Median of ${after.settings.runs} runs, (min–max) in brackets. Google Chrome ${after.environment.chrome}, headless, CPU throttling ×${after.settings.cpuThrottlingRate}, ` +
    `${after.settings.viewport.width}×${after.settings.viewport.height} @ DPR ${after.settings.deviceScaleFactor}, ${after.environment.machine}.`,
  `Before: \`${before.url}\` at commit ${before.commit} (${before.date}). After v1: commit ${afterV1.commit}. After: \`${after.url}\` at commit ${after.commit} (${after.date}).`,
  `Worker busy time before first render (final, per run): ${after.iterations.map((i) => i.workerMs).join(', ')} ms.`,
];

const START = '<!-- table:start (generated by `pnpm perf:report` from perf/results-*.json — do not edit) -->';
const END = '<!-- table:end -->';
const doc = readFileSync('PERF.md', 'utf8');
const i = doc.indexOf(START);
const j = doc.indexOf(END);
if (i === -1 || j === -1) throw new Error('table markers not found in PERF.md');
writeFileSync('PERF.md', `${doc.slice(0, i + START.length)}\n${lines.join('\n')}\n${doc.slice(j)}`);
console.log(lines.join('\n'));
